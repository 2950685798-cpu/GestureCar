/**
  ******************************************************************************
  * @file    button.h
  * @brief   独立按键检测模块接口（HAL 库通用，可移植）
  *
  *          配套 button.c 使用。移植到别的工程时，只需修改下方"用户配置区"。
  ******************************************************************************
  */
#ifndef __BUTTON_H
#define __BUTTON_H

#include "main.h"

/*==================================== 用户配置区（移植时只改这里） ====================================*/
/* 按键引脚：本工程为 PA15（内部上拉，按下接地） */
#define BUTTON_PORT				GPIOA
#define BUTTON_PIN				GPIO_PIN_15

/* 按下时的电平与上拉/下拉方式（二选一，两行配套修改）：
   接法 1（常用）：按键一端接引脚、另一端接 GND   -> 按下电平 0，配上拉（本工程用这个）
   接法 2：      按键一端接引脚、另一端接 3.3V   -> 按下电平 1，配下拉 */
#define BUTTON_PRESSED_LEVEL	0
#define BUTTON_PULL				GPIO_PULLUP

/* 消抖时间（毫秒）：按一下偶尔被识别成好几下时加大（比如 50） */
#define BUTTON_DEBOUNCE_MS		20

/*==================================== 接口函数 ====================================*/
void    Button_Init(void);			/* 引脚初始化：在 main 的初始化区调用一次 */
uint8_t Button_ReadEvent(void);		/* 按下事件：一次按下只返回一次 1（带消抖） */
uint8_t Button_IsPressed(void);		/* 实时状态：按住期间持续返回 1（无消抖） */

#endif /* __BUTTON_H */
